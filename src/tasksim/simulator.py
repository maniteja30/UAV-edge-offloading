from __future__ import annotations

from dataclasses import dataclass, field
from itertools import combinations_with_replacement
from math import ceil, log2, sqrt
import heapq
from typing import Dict, List, Tuple
import copy
import random
import statistics


@dataclass
class Config:
    """Report-aligned base configuration plus explicitly labelled assumptions.

    If task_count is None, tasks are generated by independent per-user Poisson
    processes over episode_duration_s. Set task_count to an integer only for
    deterministic smoke tests.
    """
    n_users: int = 10
    n_edges: int = 3
    helpers_per_source: int = 2
    input_mb: float = 2.0
    output_mb: float = 0.1
    cpu_cycles: float = 5e8
    memory_mb: float = 256.0
    deadline_s: float = 2.0
    subtasks: int = 2

    # Workload settings from the report.
    episode_duration_s: float = 60.0
    arrival_rate_per_user: float = 0.5
    task_count: int | None = None
    seed: int = 7

    # Base system settings from the report.
    area_width_m: float = 500.0
    area_height_m: float = 500.0
    uav_altitude_m: float = 100.0
    user_cpu_hz: float = 4e9
    edge_cpu_hz: float = 10e9
    cloud_cpu_hz: float = 100e9
    bandwidth_hz: float = 20e6

    # Explicit assumptions: the report does not specify numerical values for
    # these radio, battery, and memory-capacity parameters.
    tx_power_w: float = 0.1
    reference_gain: float = 1e-3
    path_loss_exponent: float = 2.2
    noise_density_w_hz: float = 1e-17
    edge_cloud_rate_bps: float = 100e6
    edge_cloud_delay_s: float = 0.035
    # Assumed maximum air-to-air radio distance; not numerically specified in the report.
    air_link_range_m: float = 700.0
    user_memory_capacity_mb: float = 1024.0
    edge_memory_capacity_mb: float = 8192.0
    cloud_memory_capacity_mb: float = 1_000_000.0
    user_battery_j: float = 500_000.0
    edge_battery_j: float = 2_000_000.0

    # Small deterministic split/aggregation workloads; values are assumptions.
    split_cycles: float = 1e6
    aggregation_cycles: float = 1e6
    cpu_energy_coefficient: float = 1e-28

    # Report objective weights and penalty.
    energy_reference_j: float = 0.1
    load_reference: float = 0.25
    deadline_penalty: float = 1.0
    w_latency: float = 0.5
    w_energy: float = 0.3
    w_load: float = 0.2


@dataclass
class Node:
    node_id: str
    kind: str
    x: float
    y: float
    cpu_hz: float
    memory_mb: float
    z: float = 100.0
    battery_j: float = float("inf")
    available_at: float = 0.0
    busy_cycles: float = 0.0


@dataclass
class Task:
    task_id: int
    source_id: str
    arrival_s: float
    input_mb: float
    output_mb: float
    cpu_cycles: float
    memory_mb: float
    deadline_s: float


@dataclass
class TaskResult:
    task_id: int
    source_id: str
    destinations: Tuple[str, str]
    latency_s: float
    energy_j: float
    load_imbalance: float
    deadline_met: bool
    objective: float
    branch_details: List[dict] = field(default_factory=list)


class OffloadingSimulator:
    def __init__(self, config: Config | None = None):
        self.cfg = config or Config()
        self.rng = random.Random(self.cfg.seed)
        self.nodes = self._make_nodes()
        self.network = self._build_network()
        self.tasks = self._make_tasks()

    def _make_nodes(self) -> Dict[str, Node]:
        cfg = self.cfg
        nodes: Dict[str, Node] = {}
        cx, cy = cfg.area_width_m / 2.0, cfg.area_height_m / 2.0
        radius = 0.36 * min(cfg.area_width_m, cfg.area_height_m)
        for i in range(cfg.n_users):
            angle = 2 * 3.141592653589793 * i / max(1, cfg.n_users)
            x = cx + radius * __import__("math").cos(angle)
            y = cy + radius * __import__("math").sin(angle)
            nodes[f"U{i}"] = Node(
                node_id=f"U{i}", kind="user", x=x, y=y,
                cpu_hz=cfg.user_cpu_hz,
                memory_mb=cfg.user_memory_capacity_mb,
                z=cfg.uav_altitude_m, battery_j=cfg.user_battery_j,
            )

        edge_positions = [
            (0.20 * cfg.area_width_m, 0.20 * cfg.area_height_m),
            (0.80 * cfg.area_width_m, 0.20 * cfg.area_height_m),
            (0.50 * cfg.area_width_m, 0.80 * cfg.area_height_m),
            (0.85 * cfg.area_width_m, 0.75 * cfg.area_height_m),
        ]
        for i in range(cfg.n_edges):
            x, y = edge_positions[i % len(edge_positions)]
            nodes[f"E{i}"] = Node(
                node_id=f"E{i}", kind="edge", x=x, y=y,
                cpu_hz=cfg.edge_cpu_hz,
                memory_mb=cfg.edge_memory_capacity_mb,
                z=cfg.uav_altitude_m, battery_j=cfg.edge_battery_j,
            )

        # Cloud is a logical backhaul endpoint; its coordinates are not used.
        nodes["CLOUD"] = Node(
            node_id="CLOUD", kind="cloud", x=cx, y=cy,
            cpu_hz=cfg.cloud_cpu_hz,
            memory_mb=cfg.cloud_memory_capacity_mb,
            z=0.0, battery_j=float("inf"),
        )
        return nodes

    def _make_tasks(self) -> List[Task]:
        """Generate a fixed smoke-test trace or per-user Poisson arrivals."""
        arrivals: List[Tuple[float, str]] = []
        if self.cfg.task_count is not None:
            # Deterministic trace retained for fast repeatable unit tests.
            for i in range(self.cfg.task_count):
                source = f"U{i % self.cfg.n_users}"
                arrivals.append((i * 0.05, source))
        else:
            rate = self.cfg.arrival_rate_per_user
            if rate <= 0:
                raise ValueError("arrival_rate_per_user must be positive")
            if self.cfg.episode_duration_s <= 0:
                raise ValueError("episode_duration_s must be positive")
            # Independent Poisson process for each User UAV. Inter-arrival
            # times are exponential with mean 1/lambda.
            for user_index in range(self.cfg.n_users):
                source = f"U{user_index}"
                arrival = self.rng.expovariate(rate)
                while arrival < self.cfg.episode_duration_s:
                    arrivals.append((arrival, source))
                    arrival += self.rng.expovariate(rate)

        arrivals.sort(key=lambda item: (item[0], item[1]))
        return [
            Task(
                task_id=i,
                source_id=source,
                arrival_s=arrival,
                input_mb=self.cfg.input_mb,
                output_mb=self.cfg.output_mb,
                cpu_cycles=self.cfg.cpu_cycles,
                memory_mb=self.cfg.memory_mb,
                deadline_s=self.cfg.deadline_s,
            )
            for i, (arrival, source) in enumerate(arrivals)
        ]

    @staticmethod
    def distance(a: Node, b: Node) -> float:
        return sqrt((a.x - b.x) ** 2 + (a.y - b.y) ** 2 + (a.z - b.z) ** 2)

    def _build_network(self) -> Dict[str, Dict[str, dict]]:
        """Build an explicit undirected U-U, U-E, E-E and E-C link graph.

        Air links are present only within ``air_link_range_m``. Every edge UAV
        has a backhaul link to the logical cloud endpoint. Link range and
        backhaul parameters are configurable assumptions, not report values.
        """
        graph: Dict[str, Dict[str, dict]] = {node_id: {} for node_id in self.nodes}
        aerial = [n for n in self.nodes.values() if n.kind in ("user", "edge")]
        for i, a in enumerate(aerial):
            for b in aerial[i + 1:]:
                distance = self.distance(a, b)
                if distance <= self.cfg.air_link_range_m:
                    rate = self._shannon_rate(a, b, distance)
                    link = {"rate_bps": rate, "distance_m": distance, "kind": "air", "delay_s": 0.0}
                    graph[a.node_id][b.node_id] = link
                    graph[b.node_id][a.node_id] = link
        cloud = self.nodes["CLOUD"]
        for edge in (n for n in self.nodes.values() if n.kind == "edge"):
            link = {"rate_bps": self.cfg.edge_cloud_rate_bps,
                    "distance_m": None, "kind": "backhaul",
                    "delay_s": self.cfg.edge_cloud_delay_s}
            graph[edge.node_id][cloud.node_id] = link
            graph[cloud.node_id][edge.node_id] = link
        return graph

    def _shannon_rate(self, a: Node, b: Node, distance: float) -> float:
        d = max(1.0, distance)
        snr = (
            self.cfg.tx_power_w * self.cfg.reference_gain * d ** (-self.cfg.path_loss_exponent)
            / (self.cfg.noise_density_w_hz * self.cfg.bandwidth_hz)
        )
        return self.cfg.bandwidth_hz * log2(1.0 + snr)

    def transmission_rate(self, a: Node, b: Node) -> float:
        """Return the configured rate for a directly connected pair, else zero."""
        if a.node_id == b.node_id:
            return float("inf")
        link = self.network.get(a.node_id, {}).get(b.node_id)
        return link["rate_bps"] if link else 0.0

    def transmission_time(self, data_mb: float, a: Node, b: Node) -> float:
        if a.node_id == b.node_id:
            return 0.0
        rate = self.transmission_rate(a, b)
        if rate <= 0.0:
            return float("inf")
        return data_mb * 8e6 / rate

    def candidates(self, source_id: str) -> List[str]:
        source = self.nodes[source_id]
        helpers = sorted(
            (n for n in self.nodes.values() if n.kind == "user" and n.node_id != source_id),
            key=lambda n: self.distance(source, n),
        )[:self.cfg.helpers_per_source]
        edges = sorted(n.node_id for n in self.nodes.values() if n.kind == "edge")
        return [source_id] + [n.node_id for n in helpers] + edges + ["CLOUD"]

    def action_pairs(self, source_id: str) -> List[Tuple[str, str]]:
        return list(combinations_with_replacement(self.candidates(source_id), self.cfg.subtasks))

    def _path(self, source_id: str, destination_id: str) -> List[str]:
        """Find the minimum-transmission-time feasible route using Dijkstra.

        The graph includes multi-hop U-U/U-E/E-E air links and E-C backhaul.
        An empty list means no route exists.
        """
        if source_id == destination_id:
            return [source_id]
        if source_id not in self.network or destination_id not in self.network:
            return []
        distances = {node_id: float("inf") for node_id in self.network}
        previous: Dict[str, str] = {}
        distances[source_id] = 0.0
        queue = [(0.0, source_id)]
        while queue:
            cost, current = heapq.heappop(queue)
            if cost != distances[current]:
                continue
            if current == destination_id:
                break
            for neighbor, link in self.network[current].items():
                rate = link["rate_bps"]
                hop_cost = 8e6 / max(1.0, rate) + link.get("delay_s", 0.0)  # seconds for 1 MB
                candidate = cost + hop_cost
                if candidate < distances[neighbor]:
                    distances[neighbor] = candidate
                    previous[neighbor] = current
                    heapq.heappush(queue, (candidate, neighbor))
        if distances[destination_id] == float("inf"):
            return []
        path = [destination_id]
        while path[-1] != source_id:
            parent = previous.get(path[-1])
            if parent is None:
                return []
            path.append(parent)
        return list(reversed(path))

    def _branch(self, task: Task, destination_id: str, nodes: Dict[str, Node]) -> dict:
        p = self.cfg.subtasks
        in_mb, out_mb = task.input_mb / p, task.output_mb / p
        cycles, memory = task.cpu_cycles / p, task.memory_mb / p
        path = self._path(task.source_id, destination_id)
        if not path:
            return {"destination": destination_id, "completion": float("inf"),
                    "energy": float("inf"), "forward": float("inf"), "queue": 0,
                    "compute": 0, "return": float("inf"), "path": [], "feasible": False}
        now = task.arrival_s
        comm_energy = 0.0
        forward = 0.0
        for u, v in zip(path, path[1:]):
            a, b = nodes[u], nodes[v]
            tx = self.transmission_time(in_mb, a, b)
            if not (tx < float("inf")):
                return {"destination": destination_id, "completion": float("inf"),
                        "energy": float("inf"), "forward": float("inf"), "queue": 0,
                        "compute": 0, "return": float("inf"), "path": path, "feasible": False}
            if a.kind == "edge" and b.kind == "cloud":
                tx += self.cfg.edge_cloud_delay_s
            forward += tx
            comm_energy += self.cfg.tx_power_w * tx
        dest = nodes[destination_id]
        if memory > dest.memory_mb:
            return {"destination": destination_id, "completion": float("inf"),
                    "energy": float("inf"), "forward": forward, "queue": 0,
                    "compute": 0, "return": 0, "path": path, "feasible": False}
        arrival_at_cpu = now + forward
        queue = max(0.0, dest.available_at - arrival_at_cpu)
        compute = cycles / dest.cpu_hz
        start = arrival_at_cpu + queue
        finish_cpu = start + compute
        dest.available_at = finish_cpu
        dest.busy_cycles += cycles
        comp_energy = self.cfg.cpu_energy_coefficient * (dest.cpu_hz ** 2) * cycles
        ret = 0.0
        for u, v in zip(reversed(path[1:]), reversed(path[:-1])):
            a, b = nodes[u], nodes[v]
            tx = self.transmission_time(out_mb, a, b)
            if not (tx < float("inf")):
                return {"destination": destination_id, "completion": float("inf"),
                        "energy": float("inf"), "forward": forward, "queue": queue,
                        "compute": compute, "return": float("inf"), "path": path, "feasible": False}
            if a.kind == "cloud" and b.kind == "edge":
                tx += self.cfg.edge_cloud_delay_s
            ret += tx
            comm_energy += self.cfg.tx_power_w * tx
        return {"destination": destination_id, "completion": finish_cpu + ret,
                "energy": comm_energy + comp_energy, "forward": forward,
                "queue": queue, "compute": compute, "return": ret,
                "path": path, "feasible": True}

    def _load_imbalance(self, nodes: Dict[str, Node]) -> float:
        # Episode-average CPU utilization approximation. The report defines
        # instantaneous utilization; event-time sampling is a later extension.
        active = [n for n in nodes.values() if n.kind in ("user", "edge")]
        horizon = self.cfg.episode_duration_s
        loads = [n.busy_cycles / (n.cpu_hz * horizon) for n in active]
        mean = sum(loads) / len(loads)
        return sum((x - mean) ** 2 for x in loads) / len(loads)

    def evaluate_pair(self, task: Task, pair: Tuple[str, str],
                      base_nodes: Dict[str, Node] | None = None) -> TaskResult:
        nodes = copy.deepcopy(base_nodes if base_nodes is not None else self.nodes)
        split = self.cfg.split_cycles / nodes[task.source_id].cpu_hz
        branches = [self._branch(task, d, nodes) for d in pair]
        if not all(b["feasible"] for b in branches):
            latency = float("inf")
            energy = float("inf")
        else:
            aggregation = self.cfg.aggregation_cycles / nodes[task.source_id].cpu_hz
            latency = split + max(b["completion"] - task.arrival_s for b in branches) + aggregation
            energy = sum(b["energy"] for b in branches)
        load = self._load_imbalance(nodes)
        penalty = max(0.0, (latency - task.deadline_s) / task.deadline_s) if latency < float("inf") else 1.0
        objective = (
            self.cfg.w_latency * latency / task.deadline_s
            + self.cfg.w_energy * energy / self.cfg.energy_reference_j
            + self.cfg.w_load * load / self.cfg.load_reference
            + self.cfg.deadline_penalty * penalty
        )
        return TaskResult(task.task_id, task.source_id, pair, latency, energy,
                          load, latency <= task.deadline_s, objective, branches)

    def run_policy(self, policy: str) -> List[TaskResult]:
        nodes = copy.deepcopy(self.nodes)
        results = []
        for task in self.tasks:
            candidates = self.candidates(task.source_id)
            pairs = list(combinations_with_replacement(candidates, self.cfg.subtasks))
            if policy == "local":
                chosen = (task.source_id, task.source_id)
            elif policy == "nearest":
                source = nodes[task.source_id]
                remote = [nodes[x] for x in candidates if x != task.source_id and nodes[x].kind != "cloud"]
                nearest = min(remote, key=lambda n: self.distance(source, n)).node_id
                chosen = (nearest, nearest)
            elif policy == "greedy":
                chosen = min(pairs, key=lambda p: self.evaluate_pair(task, p, nodes).objective)
            else:
                raise ValueError(f"Unknown policy: {policy}")
            result = self.evaluate_pair(task, chosen, nodes)
            for branch in result.branch_details:
                if branch["feasible"]:
                    d = nodes[branch["destination"]]
                    d.available_at = max(
                        d.available_at,
                        task.arrival_s + branch["forward"] + branch["queue"] + branch["compute"],
                    )
                    d.busy_cycles += task.cpu_cycles / self.cfg.subtasks
            results.append(result)
        return results

    @staticmethod
    def summarize(results: List[TaskResult]) -> dict:
        latencies = [r.latency_s for r in results]
        energies = [r.energy_j for r in results]
        if latencies:
            ordered = sorted(latencies)
            p95 = ordered[max(0, ceil(0.95 * len(ordered)) - 1)]
        else:
            p95 = 0.0
        return {
            "tasks": len(results),
            "mean_latency_s": statistics.mean(latencies) if latencies else 0.0,
            "p95_latency_s": p95,
            "mean_energy_j": statistics.mean(energies) if energies else 0.0,
            "deadline_violation_rate": sum(not r.deadline_met for r in results) / len(results) if results else 0.0,
            "success_rate": sum(r.deadline_met for r in results) / len(results) if results else 0.0,
            "mean_load_imbalance": statistics.mean(r.load_imbalance for r in results) if results else 0.0,
        }
